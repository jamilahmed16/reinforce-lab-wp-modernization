import tinycss2, json, re
src = open('bootstrap-4.min.css').read()
used = set(json.load(open('used.json')))
def split_sel(prelude):
    parts, cur = [], []
    for t in prelude:
        if t.type == 'literal' and t.value == ',': parts.append(tinycss2.serialize(cur).strip()); cur = []; continue
        cur.append(t)
    parts.append(tinycss2.serialize(cur).strip()); return [p for p in parts if p]
out_rules = []
def build(rs):
    out = []
    for r in rs:
        if r.type == 'qualified-rule':
            keep = [s for s in split_sel(r.prelude) if s in used]
            if keep: out.append(','.join(keep) + '{' + tinycss2.serialize(r.content).strip() + '}')
        elif r.type == 'at-rule' and r.lower_at_keyword in ('media', 'supports'):
            inner = build(tinycss2.parse_rule_list(r.content, skip_comments=True, skip_whitespace=True))
            if inner: out.append('@' + r.at_keyword + ' ' + tinycss2.serialize(r.prelude).strip() + '{' + ''.join(inner) + '}')
        elif r.type == 'at-rule' and r.lower_at_keyword.endswith('keyframes'):
            out.append(('KF', tinycss2.serialize(r.prelude).strip(), '@' + r.at_keyword + ' ' + tinycss2.serialize(r.prelude).strip() + '{' + tinycss2.serialize(r.content).strip() + '}'))
    return out
rules = build(tinycss2.parse_stylesheet(src, skip_comments=True, skip_whitespace=True))
body = ''.join(x for x in rules if isinstance(x, str))
kf = [x for x in rules if not isinstance(x, str) and re.search(r'\b' + re.escape(x[1]) + r'\b', body)]
css = body + ''.join(k[2] for k in kf)
css = '/*! Bootstrap v4.6.1 (https://getbootstrap.com/), Copyright 2011-2021 The Bootstrap Authors and Twitter, Inc., MIT licence. Trimmed to the rules used on the lean pages (D-174). Generated by claude/tools/bs-trim; do not edit by hand. */\n' + css + '\n'
open('bootstrap-lean.css', 'w').write(css)
import gzip; print(len(css), 'bytes,', len(gzip.compress(css.encode())), 'gzip; keyframes kept', [k[1] for k in kf])
