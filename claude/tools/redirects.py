#!/usr/bin/env python3
"""Build the redirect module from the approved map (A4, D-181).

  python3 claude/tools/redirects.py build   # writes wp/novamira-sandbox/core/reinforce-redirects-map.php
  python3 claude/tools/redirects.py stats   # what the map holds
  python3 claude/tools/redirects.py htaccess   # claude/rebuild/htaccess-410.conf (server 410s for old /wp-content/ files)

Source of truth: claude/data/redirect-map-draft.csv (803 rows, 0 undecided; signed off in D-181).
Never edit the generated PHP by hand; change the CSV (with Jamil's approval per URL, Rule 2) and rebuild.

Rules:
- One rule per path. Rows whose old address has a query string (?add-to-cart=...) follow their path's rule.
- 301 rows go to their target. 410 rows only apply when WordPress would otherwise answer 404
  (reinforce-redirects.php), so a removal can never hide a page that exists.
- KEEP, KEEP-NOINDEX, CONFIG rows produce nothing, except kept addresses that production already answers 404:
  they go in a '404' list so WordPress does not guess a nearby page for them (no change from production).
- Rows whose target is their own path (double slash, missing slash, duplicate slug variants) are left to
  WordPress's canonical redirect.
- Paths handled elsewhere are left out: /author/... and /paged-N/ junk (blog/reinforce-blog.php).
"""
import collections
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'claude', 'data', 'redirect-map-draft.csv')
OUT = os.path.join(ROOT, 'wp', 'novamira-sandbox', 'core', 'reinforce-redirects-map.php')


def norm(path):
    path = path.split('?', 1)[0].split('#', 1)[0].strip()
    if not path.startswith('/'):
        path = '/' + path
    return path


def load():
    rows = list(csv.DictReader(open(SRC)))
    rules, conflicts, skipped = {}, [], collections.Counter()
    for r in rows:
        act = r['action'].strip()
        path = norm(r['old_path'])
        has_query = '?' in r['old_path']
        if act.startswith('KEEP') and r['prod_status'].strip() == '404' and not has_query:
            rules.setdefault(path, ('404', ''))  # production already answers 404: no guessed redirect here either
            continue
        if act.startswith('301'):
            kind, target = '301', norm(r['target']) if r['target'].startswith('/') else r['target'].strip()
        elif act == '410':
            kind, target = '410', ''
        else:
            skipped[act] += 1
            continue
        if kind == '301' and target == path:
            skipped['variant of its own target (WordPress canonical handles it)'] += 1
            continue
        if path.startswith('/author/') or '/paged-' in path:
            skipped['handled in blog/reinforce-blog.php'] += 1
            continue
        if has_query and path in rules:
            continue  # the path's own rule decides
        if path in rules and rules[path] != (kind, target):
            conflicts.append((path, rules[path], (kind, target)))
            continue
        rules[path] = (kind, target)
    return rows, rules, conflicts, skipped


def php_str(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def build():
    rows, rules, conflicts, skipped = load()
    if conflicts:
        for c in conflicts:
            print('CONFLICT', c)
        sys.exit('Conflicting rules for the same path: fix the CSV first.')
    r301 = {p: t for p, (k, t) in rules.items() if k == '301'}
    r410 = sorted(p for p, (k, t) in rules.items() if k == '410')
    r404 = sorted(p for p, (k, t) in rules.items() if k == '404')
    # flatten chains: every old address goes straight to its final approved page (one hop)
    flattened = []
    for p in list(r301):
        seen, t = {p}, r301[p]
        while t in r301 and t not in seen:
            seen.add(t); t = r301[t]
        if t != r301[p]:
            flattened.append((p, r301[p], t)); r301[p] = t
    loops = [p for p, t in r301.items() if t == p]
    chains = [(p, t, r301[t]) for p, t in r301.items() if t in r301]
    for f in flattened:
        print('one hop:', f[0], 'now straight to', f[2], '(was via', f[1] + ')')
    if loops:
        sys.exit('Redirect to itself: %s' % loops)
    lines = ['<?php',
             '/* GENERATED by claude/tools/redirects.py from claude/data/redirect-map-draft.csv. Do not edit by hand. */',
             "if (!defined('ABSPATH')) exit;",
             'function rl_redirect_rules() {',
             '    return [',
             "        '301' => ["]
    for p in sorted(r301):
        lines.append('            %s => %s,' % (php_str(p), php_str(r301[p])))
    lines += ["        ],", "        '410' => ["]
    for p in r410:
        lines.append('            %s => 1,' % php_str(p))
    lines += ["        ],", "        '404' => ["]
    for p in r404:
        lines.append('            %s => 1,' % php_str(p))
    lines += ["        ],", '    ];', '}', '']
    open(OUT, 'w').write('\n'.join(lines))
    print('wrote', os.path.relpath(OUT, ROOT), '| 301:', len(r301), '| 410:', len(r410), '| 404 kept as on production:', len(r404), '| skipped:', dict(skipped))
    if chains:
        print('WARNING, two hops (target is itself redirected):')
        for c in chains:
            print('  ', c)


HTACCESS = os.path.join(ROOT, 'claude', 'rebuild', 'htaccess-410.conf')


def htaccess():
    """Server rules for approved 410s that WordPress never sees (old files under /wp-content/). A rule applies only
    when the file is missing, so old images that kept posts still use (D-178) are served as normal."""
    import re as _re
    rows, rules, conflicts, skipped = load()
    paths = sorted(p for p, (k, t) in rules.items() if k == '410' and p.startswith('/wp-content/'))
    lines = ['# BEGIN Reinforce Lab 410 (generated by claude/tools/redirects.py htaccess; do not edit by hand)',
             '# Approved removals (D-181) of old files under /wp-content/. Only when the file does not exist.',
             '<IfModule mod_rewrite.c>', 'RewriteEngine On']
    for p in paths:
        lines += ['RewriteCond %{REQUEST_FILENAME} !-f', 'RewriteRule ^' + _re.escape(p.lstrip('/')).replace('\\/', '/') + '$ - [G,L]']
    lines += ['</IfModule>', '# END Reinforce Lab 410', '']
    open(HTACCESS, 'w').write('\n'.join(lines))
    print('wrote', os.path.relpath(HTACCESS, ROOT), '|', len(paths), 'old files answer 410 when missing')


def stats():
    rows, rules, conflicts, skipped = load()
    print(len(rows), 'rows;', collections.Counter(k for k, t in rules.values()), '; skipped', dict(skipped), '; conflicts', len(conflicts))


if __name__ == '__main__':
    {'build': build, 'stats': stats, 'htaccess': htaccess}[sys.argv[1] if len(sys.argv) > 1 else 'stats']()
